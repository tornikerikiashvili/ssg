<script>
(() => {
    const choice = document.getElementById('download-asset');
    const basketModal = document.getElementById('download-basket');
    const storageKey = 'smartsoft-asset-cart-v2-{{ auth()->id() }}';
    let basket = [], selectedAsset = null, activeModal = null, returnFocus = null, busy = false;
    try {
        const stored = JSON.parse(sessionStorage.getItem(storageKey) || '[]');
        if (Array.isArray(stored)) basket = stored.filter(asset => Number.isInteger(asset.id) && typeof asset.title === 'string').slice(0, 50);
    } catch {}
    const error = basketModal.querySelector('[data-basket-error]');
    const downloadButton = basketModal.querySelector('[data-download-basket]');
    function closeModal(restoreFocus = true) {
        if (!activeModal) return;
        activeModal.classList.remove('is-opened');
        activeModal.style.display = 'none';
        activeModal = null;
        document.body.classList.remove('is-no-scroll');
        if (restoreFocus && returnFocus?.isConnected) returnFocus.focus();
    }
    function openModal(modal, trigger) {
        closeModal(false);
        if (trigger) returnFocus = trigger;
        activeModal = modal;
        modal.style.display = 'flex';
        document.body.classList.add('is-no-scroll');
        requestAnimationFrame(() => modal.classList.add('is-opened'));
        modal.querySelector('button, a[href]').focus();
    }
    function formatSize(bytes) {
        if (!Number.isFinite(bytes) || bytes <= 0) return 'Size unavailable';
        if (bytes < 1024) return bytes + ' B';
        if (bytes < 1024 * 1024) return (bytes / 1024).toFixed(1) + ' KB';
        return (bytes / (1024 * 1024)).toFixed(1) + ' MB';
    }
    function render() {
        try { sessionStorage.setItem(storageKey, JSON.stringify(basket)); } catch {}
        document.querySelector('[data-basket-count]').textContent = basket.length;
        const list = basketModal.querySelector('[data-basket-items]');
        list.replaceChildren();
        if (!basket.length) {
            const empty = document.createElement('p'); empty.textContent = 'Your basket is empty. Add assets from a game or the Download Center.'; list.append(empty);
        }
        basket.forEach(asset => {
            const row = document.getElementById('basket-row-template').content.cloneNode(true);
            row.querySelector('[data-item-title]').textContent = asset.title;
            row.querySelector('[data-item-size]').textContent = formatSize(asset.size);
            row.querySelector('[data-item-type]').textContent = asset.type || 'FILE';
            const icons = { PNG: 'PNG.svg', MP4: 'mp4.svg', EPS: 'EPS.svg' };
            const preview = row.querySelector('img');
            preview.classList.toggle('downloads_icon-jpeg', ['jpg', 'jpeg'].includes(String(asset.type || '').toLowerCase()));
            preview.alt = asset.title + ' preview';
            preview.onerror = () => {
                preview.onerror = null;
                preview.classList.remove('downloads_icon-jpeg');
                preview.src = @json(asset('client-design/images')) + '/' + (icons[asset.type] || 'Zip.svg');
            };
            preview.src = @json(route('resources.preview', '__RESOURCE__')).replace('__RESOURCE__', String(asset.id));
            const remove = row.querySelector('[data-remove-asset]');
            remove.setAttribute('aria-label', 'Remove ' + asset.title);
            remove.addEventListener('click', event => { event.preventDefault(); if (busy) return; basket = basket.filter(item => item.id !== asset.id); error.hidden = true; render(); downloadButton.focus(); });
            list.append(row);
        });
        downloadButton.setAttribute('aria-disabled', String(busy || !basket.length));
        downloadButton.style.opacity = busy || !basket.length ? '.3' : '';
        downloadButton.querySelector('.button_text').textContent = busy ? 'Preparing download…' : 'Download All';
    }
    document.querySelector('[data-open-basket]').addEventListener('click', event => { event.preventDefault(); openModal(basketModal, event.currentTarget); });
    document.addEventListener('click', event => {
        const trigger = event.target.closest('[data-choose-asset]');
        if (!trigger) return;
        event.preventDefault();
        selectedAsset = { id: Number(trigger.dataset.assetId), title: trigger.dataset.assetTitle, type: trigger.dataset.assetType, size: Number(trigger.dataset.assetSize) };
        choice.querySelector('[data-download-now]').href = trigger.href;
        openModal(choice, trigger);
    });
    document.querySelectorAll('[data-close-asset-dialog]').forEach(button => button.addEventListener('click', () => closeModal()));
    choice.querySelector('[data-download-now]').addEventListener('click', () => closeModal());
    choice.querySelector('[data-add-asset]').addEventListener('click', () => {
        if (!selectedAsset) return;
        error.hidden = true;
        if (!basket.some(asset => asset.id === selectedAsset.id)) {
            if (basket.length >= 50) { error.textContent = 'Your basket is full. Remove an asset first (50 files maximum).'; error.hidden = false; }
            else basket.push(selectedAsset);
        }
        render(); openModal(basketModal);
    });
    document.addEventListener('keydown', event => {
        if (!activeModal) return;
        if (event.key === 'Escape') { event.preventDefault(); closeModal(); }
        if (event.key === 'Tab' && activeModal) {
            const items = [...activeModal.querySelectorAll('button, a[href]')].filter(el => !el.disabled && el.offsetParent !== null);
            const first = items[0], last = items[items.length - 1];
            if (event.shiftKey && document.activeElement === first) { event.preventDefault(); last.focus(); }
            else if (!event.shiftKey && document.activeElement === last) { event.preventDefault(); first.focus(); }
        }
    });
    downloadButton.addEventListener('click', async event => {
        event.preventDefault();
        if (busy || !basket.length) return;
        busy = true; error.hidden = true; render();
        try {
            const response = await fetch(@json(route('assets.basket.archive')), {
                method: 'POST', headers: { 'Content-Type': 'application/json', Accept: 'application/json', 'X-CSRF-TOKEN': @json(csrf_token()) },
                body: JSON.stringify({ ids: basket.map(asset => asset.id) })
            });
            if (!response.ok) {
                let message = 'Download failed. Please try again.';
                if (response.status === 404) message = 'An asset is no longer available. Remove it from the basket and try again.';
                else if ([401, 419].includes(response.status)) message = 'Your session expired. Reload the page and sign in again.';
                else if ([422, 429].includes(response.status)) { const data = await response.json(); message = data.message || message; }
                throw new Error(message);
            }
            const url = URL.createObjectURL(await response.blob());
            const link = document.createElement('a'); link.href = url; link.download = 'game-assets.zip'; document.body.append(link); link.click(); link.remove();
            setTimeout(() => URL.revokeObjectURL(url), 60000);
        } catch (exception) { error.textContent = exception.message; error.hidden = false; }
        finally { busy = false; render(); }
    });
    render();
})();
